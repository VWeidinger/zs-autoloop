"""Build the ldb_models training command and the run scripts for one run (one seed of one spec).

Mirrors what octopus' exp_train_model does (main.py --mode train ..., run_exp inside screen), with
two differences: every run gets its own code snapshot (runs on different branches must not share
an rsynced repo) and all outputs go to the agent root.
"""

from __future__ import annotations

import hashlib
import shlex
from pathlib import Path
from typing import List

from .config import Config
from .spec import Spec


def run_dir(cfg: Config, run_id: str) -> Path:
    return cfg.runs_dir / run_id


def wandb_name(cfg: Config, spec: Spec, seed: int) -> str:
    return f"{cfg['name']}/{spec.id}/s{seed}"


def train_command(cfg: Config, spec: Spec, seed: int) -> List[str]:
    rid = f"{spec.id}-s{seed}"
    out = cfg.agent_root
    cmd = [
        "python", "main.py", "--mode", "train",
        "--wandb_project", cfg["wandb"]["project"],
        "--wandb_entity", cfg["wandb"]["entity"],
        "--wandb_group", cfg["wandb"]["group"],
        "--wandb_name", wandb_name(cfg, spec, seed),
        "--model_type", spec.model_type,
        "--device", "cuda:0",
        "--model_dir", str(out / "models" / rid),
        "--target_dir", str(out / "evaluation" / rid),
        "--statistics_file", str(cfg.resolve_data(spec.statistics_file)),
        "--seed", str(seed),
        "--version", str(spec.version),
        "--workload_runs", *[str(cfg.resolve_data(w)) for w in spec.expanded_train_workloads(cfg)],
        "--test_workload_runs", *[str(cfg.resolve_data(w)) for w in cfg["test_workloads"]],
        "--qo_eval_after_each_epoch",
        *spec.extra_args,
    ]
    return cmd


def lock_hash(repo_snapshot: Path) -> str:
    lock = repo_snapshot / "uv.lock"
    return hashlib.sha256(lock.read_bytes()).hexdigest()[:12] if lock.exists() else "nolock"


def inner_script(cfg: Config, spec: Spec, seed: int, venv: Path) -> str:
    """Runs on the GPU node inside run_exp. All paths are on the shared /mnt/labstore."""
    rid = f"{spec.id}-s{seed}"
    rd = run_dir(cfg, rid)
    code = rd / "code"
    uv = cfg["cluster"]["uv"]
    cmd = " ".join(shlex.quote(c) for c in train_command(cfg, spec, seed))
    return f"""#!/usr/bin/env bash
# generated by autoloop.harness - do not edit
set -euo pipefail
echo "$(date -Is) start on $(hostname) gpu=${{CUDA_VISIBLE_DEVICES}}" > {rd}/started
[ -f {cfg.agent_root}/.secrets/wandb.env ] && source {cfg.agent_root}/.secrets/wandb.env
export UV_PROJECT_ENVIRONMENT={venv}
# interpreter on labstore too: home directories are not shared between the nodes
export UV_PYTHON_INSTALL_DIR={cfg.agent_root}/python
export PYTHONPATH={code}/src
export PYTHONHASHSEED=0
export WANDB_RUN_GROUP={cfg['wandb']['group']}
# one venv per uv.lock hash on labstore; the first run builds it, the others wait on the lock
mkdir -p {venv.parent}
flock {venv}.lock {uv} sync --frozen --no-install-project --project {code} --python {cfg['cluster']['python']}
cd {code}/src/ldb_models
{uv} run --frozen --no-sync --project {code} {cmd}
"""


def outer_script(cfg: Config, spec: Spec, seed: int, gpu: int) -> str:
    """Started in a detached screen on the node; registers the job with run_exp like octopus does."""
    rid = f"{spec.id}-s{seed}"
    rd = run_dir(cfg, rid)
    tier = cfg["tiers"][spec.tier]
    excl = "-ex " if cfg["cluster"].get("run_exp_exclusive") else ""
    msg = f"{cfg['name']} {rid}"
    return f"""#!/usr/bin/env bash
# generated by autoloop.harness - do not edit
export CUDA_VISIBLE_DEVICES={gpu}
echo $$ > {rd}/pid
run_exp {excl}-m {shlex.quote(msg)} -n {gpu} -t {tier['expected_runtime']} -- bash {rd}/inner.sh > {rd}/train.log 2>&1
echo $? > {rd}/exit_code
"""
